# ======================================================================
def validate():
    print("\n" + "#" * 72 + "\n#  VALIDATION\n" + "#" * 72)

    # (1) noise curve sanity: sqrt(Sn) minimum should be a few x 1e-21
    #     near ~4-10 mHz (RCL Fig. 1)
    fg = np.logspace(-5, 0, 2000)
    s = np.sqrt(Sn_LISA(fg))
    imin = np.argmin(s)
    print(f"  [noise] min sqrt(Sn) = {s[imin]:.3e} Hz^-1/2 "
          f"at f = {fg[imin]:.3e} Hz  (RCL sky-averaged floor ~1.2e-20)")

    # (2) vacuum-phase sanity: leading term ~ x^(-5/3)
    b = Binary(1e6, 5e5)
    f0 = 1e-3
    x = x_of_f(f0, b)
    lead = 3.0 / 128.0 * x ** (-5 / 3)
    full = psi_vacuum(f0, b)
    print(f"  [vacuum] Mc = {b.Mc/Msun:.4g} Msun; Psi_lead = {lead:.4e}, "
          f"Psi_1PN/Psi_lead - 1 = {full/lead - 1:.3e}")

    # (3) ratio checks against paper Eqs. (4.21), (4.23), (4.27)
    #     evaluated at f = 1 Hz, rho0 = 1 g/cm^3, solar-mass-scale binary
    bb = Binary(2.0, 1.0)          # m> = 2, m< = 1
    f0 = 1.0
    ratio_halo = psi_halo(f0, bb, 1.0) / (3 / 128 * x_of_f(f0, bb) ** (-5 / 3))
    print(f"  [4.21]  Psi_halo/Psi_gw = {ratio_halo:.2e}  (paper ~2e-8, "
          f"mass-independent)")
    ratio_acc = abs(psi_acc_high(f0, bb, 1.0, include=(1,))) \
        / (3 / 128 * x_of_f(f0, bb) ** (-5 / 3))
    est_423 = 0.1 * (2.0) ** 4 * (2.0) ** (-5.0 / 3.0)
    print(f"  [4.23]  |Psi_acc,>|/Psi_gw = {ratio_acc:.2e}  "
          f"(paper order-of-magnitude estimate {est_423:.2e})")

    # (4) MBBH threshold benchmark: paper finds rho0* ~ 8e-13 g/cm^3
    #     (LISA, SNR = 3e4).  Comparable masses -> no dynamical friction.
    r = analyse_system("LISA-MBBH benchmark", 1e6, 5e5, 3e4, verbose=False)
    print(f"  [Table IV] MBBH sigma(rho0)_acc = "
          f"{r['sigma_single']['acc']:.2e} g/cm^3  "
          f"(paper Fisher result ~8e-13; same order expected)")
    return r

