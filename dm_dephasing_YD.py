def run_analysis():
    validate()

    # ---- Boudon Table II/III LISA events with dynamical friction ----
    systems = [
        ("LISA-IMRI", 1.0e4, 10.0, 64.0),
        ("LISA-EMRI", 1.0e5, 10.0, 22.0),
    ]
    results = [analyse_system(*s) for s in systems]

    # ---- sweeps ------------------------------------------------------
    print("\n" + "#" * 72 + "\n#  SWEEP 1: |r_AB| vs primary mass "
          "(q = 1e4, SNR = 30)\n" + "#" * 72)
    ms = sweep_mass()
    for m1, rab, rab0, sig, deg, cond in ms:
        print(f"   m1 = {m1:9.3e}  r_AB = {rab:+.6f}  "
              f"(DM-only {rab0:+.6f})   degr x{deg:6.1f}   cond {cond:.2e}")

    print("\n" + "#" * 72 + "\n#  SWEEP 2: r_AB vs DF-threshold location "
          "f_df^+/fmax (EMRI)\n" + "#" * 72)
    fs = sweep_fdfplus("LISA-EMRI", 1e5, 10.0, 22.0)
    for R, rab, rab0, deg in fs:
        print(f"   f_df^+/fmax = {R:8.2f}   r_AB = {rab:+.6f}   "
              f"(DM-only {rab0:+.6f})   degr x{deg:6.1f}")

