import numpy as np
import csv

# ----------------------------------------------------------------------
# Physical constants (SI)
# ----------------------------------------------------------------------
G     = 6.67430e-11        # m^3 kg^-1 s^-2
c     = 2.99792458e8       # m s^-1
Msun  = 1.98892e30         # kg
GCM3  = 1.0e3              # 1 g/cm^3 in kg/m^3
YR    = 3.15576e7          # s
FSTAR = 0.66               # critical-flux constant, Sec. II of 2305.18540

# ======================================================================
# 1.  LISA noise: Robson, Cornish & Liu (2019), arXiv:1803.01944
# ======================================================================
L_ARM  = 2.5e9             # m
F_STAR = 19.09e-3          # Hz  (c / 2 pi L)

# 4-yr galactic-confusion fit parameters, Table 1 of RCL
_CONF = dict(A=9.0e-45, alpha=0.138, beta=-221.0, kappa=521.0,
             gamma=1680.0, fk=0.00113)


def P_oms(f):
    """Optical-metrology single-link noise, RCL Eq. (10) [m^2/Hz]."""
    return (1.5e-11) ** 2 * (1.0 + (2.0e-3 / f) ** 4)


def P_acc(f):
    """Single test-mass acceleration noise, RCL Eq. (11) [m^2 s^-4/Hz]."""
    return (3.0e-15) ** 2 * (1.0 + (0.4e-3 / f) ** 2) \
        * (1.0 + (f / 8.0e-3) ** 4)


def S_conf(f):
    """Galactic confusion noise, RCL Eq. (14), 4-yr mission [1/Hz]."""
    p = _CONF
    return p['A'] * f ** (-7.0 / 3.0) \
        * np.exp(-f ** p['alpha'] + p['beta'] * f * np.sin(p['kappa'] * f)) \
        * (1.0 + np.tanh(p['gamma'] * (p['fk'] - f)))


def Sn_LISA(f):
    """Full sky-averaged LISA sensitivity, RCL Eq. (1) + confusion [1/Hz]."""
    inst = (10.0 / (3.0 * L_ARM ** 2)) \
        * (P_oms(f) + 4.0 * P_acc(f) / (2.0 * np.pi * f) ** 4) \
        * (1.0 + 0.6 * (f / F_STAR) ** 2)
    return inst + S_conf(f)

# ======================================================================
# 2.  Binary system
# ======================================================================
class Binary:
    def __init__(self, m1_Msun, m2_Msun):
        # convention m1 >= m2
        if m2_Msun > m1_Msun:
            m1_Msun, m2_Msun = m2_Msun, m1_Msun
        self.m1 = m1_Msun * Msun
        self.m2 = m2_Msun * Msun
        self.m = self.m1 + self.m2
        self.mu = self.m1 * self.m2 / self.m
        self.nu = self.mu / self.m
        self.Mc = self.nu ** 0.6 * self.m

    # -- characteristic frequencies -----------------------------------
    def f_isco(self):
        return c ** 3 / (6.0 ** 1.5 * np.pi * G * self.m)

    def f_gamma(self):
        """v^2 = 0.137 c^2 relativistic-validity cut (Sec. IV.B.5)."""
        return 0.137 ** 1.5 * c ** 3 / (np.pi * G * self.m)

    def f_obs(self, Tobs=4.0 * YR):
        """GW frequency Tobs before merger (paper Sec. VI.A)."""
        return 4.149e-5 * (self.Mc / (1e6 * Msun)) ** (-5.0 / 8.0) \
            * (Tobs / YR) ** (-3.0 / 8.0)

    def lisa_band(self):
        """Boudon Table I: fmin = max(2e-5, f_obs); fmax = min(1, f_gamma)."""
        fmin = max(2.0e-5, self.f_obs())
        fmax = min(1.0, self.f_gamma())
        return fmin, fmax

    # -- regime thresholds, Eqs. (5.5)-(5.8) inverted for f -----------
    def f_acc(self, i, y):
        """Accretion threshold frequency for BH i (1 or 2)."""
        mi = self.m1 if i == 1 else self.m2
        return c ** 3 * mi ** 3 \
            / (3.0 * np.pi * FSTAR * G * self.m * self.mu ** 3 * y)

    def f_df_minus(self, y):
        """Lower dynamical-friction threshold for the smaller BH."""
        return c ** 3 * self.m2 ** 3 \
            / (np.pi * G * self.m * self.mu ** 3 * y ** 1.5)

    def _log_fdf_plus_y1(self):
        """log of f_df^+ at y = 1 (computed in log space: mu^15 etc.
        overflow float64 for supermassive systems)."""
        return (3.0 + 3.0 * np.log(c) + 5.0 * np.log(self.m)
                + 15.0 * np.log(self.mu) - np.log(5832.0 * np.pi * G)
                - 21.0 * np.log(self.m2))

    def f_df_plus(self, y):
        """Upper dynamical-friction threshold for the smaller BH."""
        return np.exp(self._log_fdf_plus_y1() - 1.5 * np.log(y))

    def y_for_fdf_plus(self, f_plus):
        """Invert f_df_plus(y) = f_plus  ->  density ratio y = rho_a/rho0."""
        return np.exp((2.0 / 3.0) * (self._log_fdf_plus_y1() - np.log(f_plus)))

# ======================================================================
# 3.  Phase model  (all Psi in radians; x = pi G Mc f / c^3)
# ======================================================================
def x_of_f(f, b):
    return np.pi * G * b.Mc * f / c ** 3


def psi_vacuum(f, b):
    """Eq. (4.16): leading + 1PN SPA phase."""
    x = x_of_f(f, b)
    onePN = (20.0 / 9.0) * (743.0 / 336.0 + 2.75 * b.nu) \
        * (np.pi * G * b.m * f / c ** 3) ** (2.0 / 3.0)
    return (3.0 / 128.0) * x ** (-5.0 / 3.0) * (1.0 + onePN)


def _dm_prefac(b, rho0_gcm3):
    """Common factor  rho0 G^3 Mc^2 / c^6  [dimensionless * s^0]."""
    rho0 = rho0_gcm3 * GCM3
    return rho0 * G ** 3 * b.Mc ** 2 / c ** 6


def psi_halo(f, b, rho0_gcm3):
    """Eq. (4.18): cloud self-gravity, -3PN,  x^(-11/3)."""
    return (25.0 * np.pi / 924.0) * _dm_prefac(b, rho0_gcm3) \
        * x_of_f(f, b) ** (-11.0 / 3.0)


def _acc_mass_factor(b, include=(1, 2)):
    """Sum_i (m_i^3 / mu^2 m)(3 + 2 m_i^2 / (m mu)) over included BHs."""
    tot = 0.0
    for i in include:
        mi = b.m1 if i == 1 else b.m2
        tot += mi ** 3 / (b.mu ** 2 * b.m) * (3.0 + 2.0 * mi ** 2 / (b.m * b.mu))
    return tot


def psi_acc_high(f, b, rho0_gcm3, include=(1, 2)):
    """Eq. (4.19), high-frequency branch (f > f_acc,i): -5.5PN, x^(-16/3).
    Proportional to the bulk density rho0."""
    return -(25.0 * np.pi / 38912.0) * _dm_prefac(b, rho0_gcm3) \
        * _acc_mass_factor(b, include) * x_of_f(f, b) ** (-16.0 / 3.0)


def psi_acc_low(f, b, rhoa_gcm3, include=(1, 2)):
    """Eq. (4.19), low-frequency branch (f < f_acc,i): -4PN, x^(-13/3).
    Proportional to rho_a; bracket terms -> 1 for f << f_acc (Eq. 5.10)."""
    mfac = sum((3.0 + 2.0 * (b.m1 if i == 1 else b.m2) ** 2 / (b.m * b.mu))
               for i in include)
    return -(75.0 * np.pi * FSTAR / 26624.0) * b.nu ** 0.4 \
        * _dm_prefac(b, rhoa_gcm3) * mfac * x_of_f(f, b) ** (-13.0 / 3.0)


def psi_df(f, b, rho0_gcm3, f_plus):
    """Eq. (4.20), main window f_df^- < f < f_df^+ (smaller BH only):
    -5.5PN carrier x^(-16/3) modulated by the Coulomb-log bracket."""
    x = x_of_f(f, b)
    r = f / f_plus
    bracket = 1.0 + (304.0 / 105.0) * np.log(r) \
        - (361.0 / 105.0) * r ** (16.0 / 3.0) \
        + (256.0 / 105.0) * r ** (19.0 / 3.0)
    mass2 = b.m2 ** 3 / (b.mu ** 2 * b.m)
    return (875.0 * np.pi / 11829248.0) * _dm_prefac(b, rho0_gcm3) \
        * mass2 * x ** (-16.0 / 3.0) * bracket

# ======================================================================
# 4.  Fisher machinery  (Eq. 5.3, phase-only, amplitude decorrelated)
# ======================================================================
def make_fgrid(fmin, fmax, n=6000):
    return np.logspace(np.log10(fmin), np.log10(fmax), n)


def fisher(derivs, fgrid, snr):
    """Gamma_ij = SNR^2 * int w dPsi_i dPsi_j / int w,  w = f^-7/3 / Sn."""
    w = fgrid ** (-7.0 / 3.0) / Sn_LISA(fgrid)
    norm = np.trapezoid(w, fgrid)
    n = len(derivs)
    Gam = np.empty((n, n))
    for i in range(n):
        for j in range(i, n):
            Gam[i, j] = Gam[j, i] = \
                snr ** 2 * np.trapezoid(w * derivs[i] * derivs[j], fgrid) / norm
    return Gam


def invert_fisher(Gam):
    """Numerically stable inversion via correlation-normalised Fisher.
    Returns (covariance, sigmas, correlation matrix, condition number)."""
    d = np.sqrt(np.diag(Gam))
    D = np.outer(d, d)
    C = Gam / D                       # unit-diagonal Fisher
    cond = np.linalg.cond(C)
    Cinv = np.linalg.inv(C)
    Sigma = Cinv / D                  # covariance
    sig = np.sqrt(np.diag(Sigma))
    corr = Sigma / np.outer(sig, sig)
    return Sigma, sig, corr, cond


def binary_param_derivs(b, fgrid):
    """Analytic d/dtc, d/dphic + numeric d/dln m1, d/dln m2 of Psi_vac."""
    d_tc = 2.0 * np.pi * fgrid
    d_phic = -np.ones_like(fgrid)
    eps = 1e-6
    out = []
    for which in ('m1', 'm2'):
        bp = Binary((b.m1 / Msun) * (1 + eps) if which == 'm1' else b.m1 / Msun,
                    (b.m2 / Msun) * (1 + eps) if which == 'm2' else b.m2 / Msun)
        bm = Binary((b.m1 / Msun) * (1 - eps) if which == 'm1' else b.m1 / Msun,
                    (b.m2 / Msun) * (1 - eps) if which == 'm2' else b.m2 / Msun)
        out.append((psi_vacuum(fgrid, bp) - psi_vacuum(fgrid, bm)) / (2 * eps))
    return d_tc, d_phic, out[0], out[1]

