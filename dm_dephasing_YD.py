# 5.  Per-system analysis
# ======================================================================
def analyse_system(name, m1, m2, snr, fdfplus_over_fmax=10.0, verbose=True):
    b = Binary(m1, m2)
    fmin, fmax = b.lisa_band()
    fgrid = make_fgrid(fmin, fmax)

    # ---- fiducial self-interaction: put the DF window around the band
    f_plus = fdfplus_over_fmax * fmax
    y = b.y_for_fdf_plus(f_plus)
    f_minus = b.f_df_minus(y)
    facc1, facc2 = b.f_acc(1, y), b.f_acc(2, y)

    # which BHs are in the HIGH-frequency accretion regime over the band?
    acc_include = tuple(i for i, fa in ((1, facc1), (2, facc2)) if fa < fmin)
    regime_ok = dict(
        df_window=(f_minus < fmin and f_plus > fmax),
        acc_high_1=(facc1 < fmin), acc_high_2=(facc2 < fmin),
        df_active=(b.nu < 0.16 or m1 / m2 > 2.6))

    # ---- mechanism templates: dPsi/drho at rho = 1 g/cm^3 (linear)
    tA = psi_acc_high(fgrid, b, 1.0, include=acc_include if acc_include else (2,))
    tB = psi_df(fgrid, b, 1.0, f_plus)
    tH = psi_halo(fgrid, b, 1.0)
    tL = psi_acc_low(fgrid, b, 1.0)

    d_tc, d_phic, d_lnm1, d_lnm2 = binary_param_derivs(b, fgrid)
    base = [d_tc, d_phic, d_lnm1, d_lnm2]

    # ---- (a) single-mechanism detection thresholds (paper's analysis)
    single = {}
    for lab, t in (('acc', tA), ('df', tB), ('halo', tH), ('acc_low', tL)):
        Gam = fisher(base + [t], fgrid, snr)
        _, sig, _, _ = invert_fisher(Gam)
        single[lab] = sig[4]                    # sigma(rho) in g/cm^3

    # ---- (b) JOINT accretion + dynamical friction (the new question)
    Gam6 = fisher(base + [tA, tB], fgrid, snr)
    Sigma6, sig6, corr6, cond6 = invert_fisher(Gam6)
    rAB = corr6[4, 5]
    degr_A = sig6[4] / single['acc']
    degr_B = sig6[5] / single['df']

    # ---- (c) DM-only joint (no binary-parameter marginalisation)
    Gam2 = fisher([tA, tB], fgrid, snr)
    _, _, corr2, _ = invert_fisher(Gam2)
    rAB_nomarg = corr2[0, 1]

    # ---- (d) full 4-mechanism shape-correlation matrix (marginalised)
    labels4 = ['halo(-3PN)', 'acc_low(-4PN)', 'acc_high(-5.5PN)', 'df(-5.5PN+log)']
    GamM = fisher(base + [tH, tL, tA, tB], fgrid, snr)
    try:
        _, _, corrM, condM = invert_fisher(GamM)
        mech_corr = corrM[4:, 4:]
    except np.linalg.LinAlgError:
        mech_corr, condM = None, np.inf

    res = dict(name=name, m1=m1, m2=m2, snr=snr, fmin=fmin, fmax=fmax,
               y=y, cs_over_c=1.0 / np.sqrt(y), f_plus=f_plus,
               f_minus=f_minus, facc1=facc1, facc2=facc2,
               acc_include=acc_include, regime_ok=regime_ok,
               sigma_single=single, sigma_joint_A=sig6[4],
               sigma_joint_B=sig6[5], rAB=rAB, rAB_nomarg=rAB_nomarg,
               degr_A=degr_A, degr_B=degr_B, cond6=cond6,
               mech_corr=mech_corr, mech_labels=labels4,
               binary=b, fgrid=fgrid, templates=dict(A=tA, B=tB, H=tH, L=tL),
               Sigma6=Sigma6)

    if verbose:
        print_report(res)
    return res


def print_report(r):
    b = r['binary']
    print(f"\n{'=' * 72}\n  {r['name']}:  m1 = {r['m1']:.3g} Msun,  "
          f"m2 = {r['m2']:.3g} Msun,  SNR = {r['snr']:.3g}")
    print(f"{'=' * 72}")
    print(f"  band            : [{r['fmin']:.3e}, {r['fmax']:.3e}] Hz   "
          f"(f_obs 4yr = {b.f_obs():.3e}, f_gamma = {b.f_gamma():.3e})")
    print(f"  fiducial y      : {r['y']:.3e}   (c_s/c = {r['cs_over_c']:.3e})")
    print(f"  DF window       : [{r['f_minus']:.3e}, {r['f_plus']:.3e}] Hz"
          f"   covers band: {r['regime_ok']['df_window']}")
    print(f"  f_acc(BH1,BH2)  : {r['facc1']:.3e}, {r['facc2']:.3e} Hz"
          f"   high-f accretion BHs included: {r['acc_include']}")
    print("\n  -- single-mechanism 1-sigma detection thresholds "
          "(marginalised over tc, phic, ln m1, ln m2) --")
    for k, v in r['sigma_single'].items():
        print(f"     sigma(rho0) [{k:8s}] = {v:.3e} g/cm^3")
    print("\n  -- JOINT accretion + dynamical friction --")
    print(f"     sigma(rho_A)  joint  = {r['sigma_joint_A']:.3e} g/cm^3"
          f"   (x {r['degr_A']:.1f} degradation)")
    print(f"     sigma(rho_B)  joint  = {r['sigma_joint_B']:.3e} g/cm^3"
          f"   (x {r['degr_B']:.1f} degradation)")
    print(f"     r_AB (marginalised)  = {r['rAB']:+.6f}")
    print(f"     r_AB (DM-only)       = {r['rAB_nomarg']:+.6f}")
    print(f"     cond(norm. Fisher)   = {r['cond6']:.3e}")
    if r['mech_corr'] is not None:
        print("\n  -- 4-mechanism correlation matrix (marginalised) --")
        print("     " + "  ".join(f"{l:>16s}" for l in r['mech_labels']))
